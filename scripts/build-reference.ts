/**
 * Vendors the canonical draw.io XML reference from jgraph/drawio-mcp into a
 * TypeScript module, so the Worker can inline it without a build-time file read
 * (Wrangler's bundler has no `?raw` import for text files).
 *
 *   bun run ref      # after updating shared/xml-essentials.md
 */
const src = new URL('../shared/xml-essentials.md', import.meta.url);
const out = new URL('../worker/reference.ts', import.meta.url);

const markdown = (await Bun.file(src).text()).trim();

if (!markdown.includes('mxGraphModel')) {
  throw new Error('shared/xml-essentials.md does not look like the draw.io reference');
}

await Bun.write(
  out,
  `// GENERATED by scripts/build-reference.ts - do not edit by hand.\n` +
    `// Source: jgraph/drawio-mcp/shared/xml-essentials.md (Apache-2.0).\n` +
    `export const REFERENCE = ${JSON.stringify(markdown)};\n`,
);

console.log(`worker/reference.ts written (${markdown.length} chars)`);
